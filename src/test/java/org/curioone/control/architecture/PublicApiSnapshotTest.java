package org.curioone.control.architecture;

import static org.junit.jupiter.api.Assertions.fail;

import java.io.IOException;
import java.lang.reflect.Constructor;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.Type;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * Locks the public API against accidental change (spec §38, PHASES M5.1).
 *
 * <p>The library is pre-1.0, so the API may still change — but every change should be deliberate
 * and appear in review. This test reflects over the compiled public and protected surface, writes
 * one line per member, and compares against a committed baseline. A rename, a removed overload, a
 * changed parameter type, or a narrowed visibility all fail here rather than at a team's build.
 *
 * <p>Regenerate the baseline after an intentional API change:
 *
 * <pre>{@code
 * CURIO_API_UPDATE=true ./gradlew test --tests "*PublicApiSnapshotTest"
 * }</pre>
 *
 * <p>Packages, private members, and synthetic members (including JaCoCo's instrumentation fields)
 * are excluded: they are not part of the contract and would make the snapshot noisy.
 */
@DisplayName("Architecture: public API snapshot")
class PublicApiSnapshotTest {

    private static final Path BASELINE =
            Paths.get("src", "test", "resources", "api", "public-api.txt");

    private static final Path CLASSES = Paths.get("build", "classes", "java", "main");

    private static final String HEADER =
            "# CurioControl public API snapshot.\n"
                    + "# Generated by PublicApiSnapshotTest; do not edit by hand.\n"
                    + "# Regenerate: CURIO_API_UPDATE=true ./gradlew test --tests "
                    + "\"*PublicApiSnapshotTest\"\n"
                    + "#\n";

    @Test
    @DisplayName("the public API matches the committed baseline")
    void publicApiMatchesBaseline() throws IOException {
        final String actual = HEADER + String.join("\n", snapshot()) + "\n";

        if ("true".equalsIgnoreCase(System.getenv("CURIO_API_UPDATE"))) {
            Files.createDirectories(BASELINE.getParent());
            Files.write(BASELINE, actual.getBytes(StandardCharsets.UTF_8));
            return;
        }

        if (!Files.exists(BASELINE)) {
            fail(
                    "No API baseline at "
                            + BASELINE
                            + ". Generate it with CURIO_API_UPDATE=true ./gradlew test "
                            + "--tests \"*PublicApiSnapshotTest\"");
        }

        final String expected = new String(Files.readAllBytes(BASELINE), StandardCharsets.UTF_8);
        if (!expected.equals(actual)) {
            fail(difference(expected, actual));
        }
    }

    private static List<String> snapshot() throws IOException {
        final List<String> lines = new ArrayList<>();
        final List<Path> classFiles;
        try (Stream<Path> walk = Files.walk(CLASSES)) {
            classFiles =
                    walk.filter(path -> path.toString().endsWith(".class"))
                            .collect(Collectors.toList());
        }

        for (Path classFile : classFiles) {
            final String name = className(CLASSES.relativize(classFile));
            if (name.equals("module-info") || name.endsWith(".package-info")) {
                continue;
            }
            if (name.contains("$jacoco")) {
                continue;
            }

            final Class<?> type;
            try {
                type = Class.forName(name, false, PublicApiSnapshotTest.class.getClassLoader());
            } catch (ClassNotFoundException e) {
                throw new IllegalStateException("Cannot load compiled class " + name, e);
            }

            if (!isApiClass(type)) {
                continue;
            }

            lines.add(describeClass(type));
            addMembers(lines, type);
        }

        Collections.sort(lines);
        return lines;
    }

    private static String className(Path relative) {
        final String path = relative.toString();
        return path.substring(0, path.length() - ".class".length())
                .replace('\\', '.')
                .replace('/', '.');
    }

    private static boolean isApiClass(Class<?> type) {
        if (type.isSynthetic()
                || type.isAnonymousClass()
                || type.isLocalClass()
                || !Modifier.isPublic(type.getModifiers())) {
            return false;
        }
        // A public nested class inside a package-private outer class is not reachable from outside.
        for (Class<?> outer = type.getEnclosingClass();
                outer != null;
                outer = outer.getEnclosingClass()) {
            if (!Modifier.isPublic(outer.getModifiers())) {
                return false;
            }
        }
        return true;
    }

    private static String describeClass(Class<?> type) {
        final StringBuilder line = new StringBuilder("class ");
        appendModifiers(line, type.getModifiers());
        line.append(type.getName());

        final Type superclass = type.getGenericSuperclass();
        if (superclass != null) {
            line.append(" extends ").append(superclass.getTypeName());
        }

        final Type[] interfaces = type.getGenericInterfaces();
        if (interfaces.length > 0) {
            line.append(type.isInterface() ? " extends " : " implements ");
            for (int i = 0; i < interfaces.length; i++) {
                if (i > 0) {
                    line.append(", ");
                }
                line.append(interfaces[i].getTypeName());
            }
        }
        return line.toString();
    }

    private static void addMembers(List<String> lines, Class<?> type) {
        for (Field field : type.getDeclaredFields()) {
            if (isApiMember(field.getModifiers(), field.getName(), field.isSynthetic())) {
                lines.add("field " + field.toGenericString());
            }
        }
        for (Constructor<?> constructor : type.getDeclaredConstructors()) {
            if (isApiMember(
                    constructor.getModifiers(), constructor.getName(), constructor.isSynthetic())) {
                lines.add("constructor " + constructor.toGenericString());
            }
        }
        for (Method method : type.getDeclaredMethods()) {
            if (isApiMember(method.getModifiers(), method.getName(), method.isSynthetic())
                    && !method.isBridge()) {
                lines.add("method " + method.toGenericString());
            }
        }
    }

    private static boolean isApiMember(int modifiers, String name, boolean synthetic) {
        return !synthetic
                && !name.startsWith("$jacoco")
                && (Modifier.isPublic(modifiers) || Modifier.isProtected(modifiers));
    }

    private static void appendModifiers(StringBuilder line, int modifiers) {
        final String text = Modifier.toString(modifiers);
        if (!text.isEmpty()) {
            line.append(text).append(' ');
        }
    }

    private static String difference(String expected, String actual) {
        final String[] expectedLines = expected.split("\n", -1);
        final String[] actualLines = actual.split("\n", -1);
        final int common = Math.min(expectedLines.length, actualLines.length);

        for (int i = 0; i < common; i++) {
            if (!expectedLines[i].equals(actualLines[i])) {
                return "Public API changed at line "
                        + (i + 1)
                        + ".\n  baseline: "
                        + expectedLines[i]
                        + "\n  current:  "
                        + actualLines[i]
                        + "\n\nIf the change is intentional, regenerate the baseline with "
                        + "CURIO_API_UPDATE=true ./gradlew test "
                        + "--tests \"*PublicApiSnapshotTest\".";
            }
        }
        return "Public API length changed: baseline has "
                + expectedLines.length
                + " lines, current has "
                + actualLines.length
                + ".\nIf the change is intentional, regenerate the baseline.";
    }
}
